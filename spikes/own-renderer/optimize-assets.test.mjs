  await copyFile(new URL("./public/pw-runtime.mjs", import.meta.url), path.join(dir, "pw-runtime.mjs"));
  const files = { "templates.json": JSON.stringify(pages.map(([page, id]) => ({ path: page, chunks: [event(id)] }))) };
