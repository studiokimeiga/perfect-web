test("the production build minifies and compresses only public client assets", async () => {
  const dir = await mkdtemp(path.join(tmpdir(), "pw-assets-"));
  try {
    const javascript = "export function answer ( ) { return 42; } // comment\n";
    const binary = Buffer.from([0x00, 0x61, 0x73, 0x6d, 0x01, 0, 0, 0]);
    const privatePage = "<html>session-specific</html>";
    await writeFile(path.join(dir, "pw-runtime.mjs"), javascript);
    await writeFile(path.join(dir, "pw-resume.wasm"), binary);
    await writeFile(path.join(dir, "Page.html"), privatePage);
    await writeFile(path.join(dir, "sources.json"), "{}");
    await writeFile(path.join(dir, "license.txt"), "licence");
    const files = await optimizeAssets(dir);
    assert.deepEqual(files, ["pw-resume.wasm", "pw-runtime.mjs"].sort());
    const minified = await readFile(path.join(dir, "pw-runtime.mjs"));
    assert.ok(minified.length < Buffer.byteLength(javascript));
    assert.match(minified.toString(), /42/);
    for (const name of files) {
      const bytes = await readFile(path.join(dir, name));
      assert.deepEqual(brotliDecompressSync(await readFile(path.join(dir, name + ".br"))), bytes);
      assert.deepEqual(gunzipSync(await readFile(path.join(dir, name + ".gz"))), bytes);
    }
    assert.equal((await readFile(path.join(dir, "Page.html"))).toString(), privatePage);
    await assert.rejects(readFile(path.join(dir, "Page.html.br")), { code: "ENOENT" });
    await assert.rejects(readFile(path.join(dir, "sources.json.br")), { code: "ENOENT" });
    assert.equal((await readFile(path.join(dir, "license.txt"))).toString(), "licence");
    const originalBr = await readFile(path.join(dir, "pw-runtime.mjs.br"));
    await optimizeAssets(dir);
    assert.deepEqual(await readFile(path.join(dir, "pw-runtime.mjs.br")), originalBr);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test("a production build compresses its compiled modules beside themselves, unchanged", async () => {
  // ADR-0399: a production page warms its handlers, computed
  // values and speculations, so each is sent with every first visit. Each
  // is compressed as it is: its bytes are its compiler's, its URL its
  // identity's, and nothing rewrites either.
  const dir = await mkdtemp(path.join(tmpdir(), "pw-assets-"));
  try {
    const handler = "// Generated by pw: resumable handler 0123456789abcdef. Do not edit.\nexport const handler = \"0123456789abcdef\";\n";
    const computed = "export const parts = { 3: (v) => v.length };\n";
    await mkdir(path.join(dir, "build/handlers"), { recursive: true });
    await mkdir(path.join(dir, "build/computed"), { recursive: true });
    await mkdir(path.join(dir, "build/components"), { recursive: true });
    await writeFile(path.join(dir, "build/handlers/0123456789abcdef.mjs"), handler);
    await writeFile(path.join(dir, "build/computed/app.Page~ui.mjs"), computed);
    await writeFile(path.join(dir, "build/handlers/README.txt"), "not a module");
    await writeFile(path.join(dir, "build/components/c.wasm"), Buffer.from([0, 0x61, 0x73, 0x6d]));
    await writeFile(path.join(dir, "pw-runtime.mjs"), "export const a = 1;\n");
    await optimizeAssets(dir);
    for (const [file, body] of [
      ["build/handlers/0123456789abcdef.mjs", handler],
      ["build/computed/app.Page~ui.mjs", computed],
    ]) {
      assert.equal((await readFile(path.join(dir, file))).toString(), body, `${file} unchanged`);
      assert.equal(brotliDecompressSync(await readFile(path.join(dir, `${file}.br`))).toString(), body);
      assert.equal(gunzipSync(await readFile(path.join(dir, `${file}.gz`))).toString(), body);
    }
    // Only modules: no other file of the build is touched.
    await assert.rejects(readFile(path.join(dir, "build/handlers/README.txt.br")), { code: "ENOENT" });
    await assert.rejects(readFile(path.join(dir, "build/components/c.wasm.br")), { code: "ENOENT" });
    // Deterministic, and a build with no compiled modules is no error.
    const again = await readFile(path.join(dir, "build/handlers/0123456789abcdef.mjs.br"));
    assert.deepEqual(await compressModules(dir), [
      "build/handlers/0123456789abcdef.mjs",
      "build/computed/app.Page~ui.mjs",
    ]);
    assert.deepEqual(await readFile(path.join(dir, "build/handlers/0123456789abcdef.mjs.br")), again);
    const empty = await mkdtemp(path.join(tmpdir(), "pw-assets-"));
    try {
      assert.deepEqual(await compressModules(empty), []);
    } finally {
      await rm(empty, { recursive: true, force: true });
    }
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

