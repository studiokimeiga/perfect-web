/** A build's files, as `pw build` lays them out. */
async function aBuild(dir, files) {
  for (const [name, body] of Object.entries(files)) {
    await mkdir(path.dirname(path.join(dir, "build", name)), { recursive: true });
    await writeFile(path.join(dir, "build", name), body);
  }
}

const event = (handler) => ({ chunk: "dynamic", value: { part: "event", id: 1, owner: 0, event: "press", handler } });
const handlerModule = (id, says) => `// Generated by pw: resumable handler ${id}. Do not edit.
function trap(what) {
  throw new Error("trap: " + what);
}
export const handler = "${id}";
export async function run(context) {
  if (context.fail) trap("asked to");
  return ${JSON.stringify(says)};
}
`;

test("a production build puts each page's code in one module, and leaves each module as it was", async () => {
  const dir = await mkdtemp(path.join(tmpdir(), "pw-assets-"));
  try {
    const a = "aaaaaaaaaaaaaaaa";
    const b = "bbbbbbbbbbbbbbbb";
    const other = "cccccccccccccccc";
    const view = "dddddddddddddddd";
    const nested = { chunk: "dynamic", value: { part: "conditional", id: 2, value: "x", then: [event(b)], otherwise: [] } };
    const instance = { chunk: "dynamic", value: { part: "instance", id: 3, path: "app.View~ui", args: [] } };
    await aBuild(dir, {
      "pages/app.Page~ui.json": "{}",
      "pages/app.Other~ui.json": "{}",
      "pages/app.Static~ui.json": "{}",
      "templates.json": JSON.stringify([
        { path: "app.Page~ui", chunks: [event(a), nested, instance, event(a)] },
        { path: "app.Other~ui", chunks: [event(other)] },
        { path: "app.Static~ui", chunks: [{ chunk: "static", value: "<p>" }] },
        { path: "app.View~ui", chunks: [event(view), instance] },
      ]),
      [`handlers/${a}.mjs`]: handlerModule(a, "a"),
      [`handlers/${b}.mjs`]: handlerModule(b, "b"),
      [`handlers/${other}.mjs`]: handlerModule(other, "other"),
      [`handlers/${view}.mjs`]: handlerModule(view, "view"),
      "computed/app.Page~ui.mjs": "export const parts = { 3: (v) => v.length };\n",
      "speculations/app.Page~ui.mjs": "export const commands = {};\n",
    });
    assert.deepEqual(await bundlePages(dir), ["app.Other~ui", "app.Page~ui"]);

    const file = path.join(dir, "build/bundles/app.Page~ui.mjs");
    const body = await readFile(file);
    assert.deepEqual(brotliDecompressSync(await readFile(`${file}.br`)), body);
    assert.deepEqual(gunzipSync(await readFile(`${file}.gz`)), body);
    assert.ok(!body.toString().includes("function trap"), "a bundle is minified");

    const url = `data:text/javascript;base64,${body.toString("base64")}`;
    const module = await import(url);
    assert.deepEqual(Object.keys(module).sort(), ["computed", `h_${a}`, `h_${b}`, `h_${view}`, "speculation"].sort());
    assert.equal(await module[`h_${a}`].run({}), "a");
    assert.equal(await module[`h_${b}`].run({}), "b");
    assert.equal(await module[`h_${view}`].run({}), "view");
    assert.equal(module[`h_${a}`].handler, a);
    assert.equal(module.computed.parts[3]("four"), 4);
    assert.deepEqual(module.speculation.commands, {});

    // A page with no code of its own has no bundle, and each module is as it was.
    await assert.rejects(readFile(path.join(dir, "build/bundles/app.Static~ui.mjs")), { code: "ENOENT" });
    assert.equal((await readFile(path.join(dir, `build/handlers/${a}.mjs`))).toString(), handlerModule(a, "a"));

    // Deterministic, as each file a delivery digests must be.
    await bundlePages(dir);
    assert.deepEqual(await readFile(file), body);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

